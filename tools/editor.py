from asset import COMPILE, FIXTURE_PINS, NAMES, copy_fixture, local_dir
from probe import ROOT, TAG, extract_tools, pe_headers, run, sha256


EXE = "VCEDIT.EXE"
WORK = ROOT / ".editor"
HDR = b"VC10\xa9 Almathera Ltd 1994\n"
UNITS = ("editor", "local", "vc10", "ilbm")
LINK = f"""system nt_win
runtime windows=4.0
option osversion=4.0, map=editor.map, verbose
name {EXE}
file {', '.join(unit + '.obj' for unit in UNITS)}
"""


def build():
    out = local_dir(WORK)
    with tempfile.TemporaryDirectory(dir=out) as folder:
        work = Path(folder)
        watcom = work / "watcom"
        extract_tools(watcom)
        bin_dir = watcom / "binnt64"
        system = Path(os.environ["SystemRoot"])
        env = {"SystemRoot": str(system), "PATH": f"{bin_dir};{system / 'System32'}",
               "WATCOM": str(watcom), "INCLUDE": f"{watcom / 'h'};{watcom / 'h' / 'nt'}",
               "TMP": folder, "TEMP": folder}
        files = {name: ROOT / "editor" / name for name in
                 ("editor.c", "local.c", "local.h", "vc10.c", "vc10.h")}
        files.update({name: ROOT / "asset" / name for name in ("ilbm.c", "ilbm.h")})
        for name, path in files.items():
            (work / name).write_bytes(path.read_bytes().replace(b"\r\n", b"\n"))
        (work / "editor.lnk").write_bytes(LINK.encode("ascii"))
        commands = [("wcc386.exe", *COMPILE, f"-fo={unit}.obj", f"{unit}.c") for unit in UNITS]
        commands.append(("wlink.exe", "@editor.lnk"))
        logs = [run(bin_dir / cmd[0], *cmd[1:], cwd=work, env=env) for cmd in commands]
        exe = work / EXE
        image = bytearray(exe.read_bytes())
        pe, opt, checksum = pe_headers(image)
        if checksum or any(image[opt + 128:opt + 136]) or any(image[opt + 144:opt + 152]):
            raise ValueError("cannot normalize checksummed, signed or debug PE")
        struct.pack_into("<I", image, pe + 8, 0)
        exe.write_bytes(image)
        dump = run(bin_dir / "wdump.exe", EXE, cwd=work, env=env)
        dlls = set(re.findall(r"^\s*DLL name = <([^>]+)>", dump, re.MULTILINE))
        if dlls != {"GDI32.DLL", "KERNEL32.DLL", "USER32.DLL"}:
            raise ValueError(f"unexpected direct imports: {dlls}")
        if "clib3r.lib(cstrtwwt)" not in (work / "editor.map").read_text():
            raise ValueError("expected Open Watcom static WinMain startup")
        hashes = [f"{sha256(work / name)}  {name}" for name in (*files, EXE)]
        (work / "PE-IMPORTS.txt").write_text(
            "\n".join([f"Open Watcom v2 {TAG}; x86 PE32 GUI 4.0; static CRT; no delay imports",
                       *(" ".join(command) for command in commands), LINK, *hashes, *logs, dump]),
            encoding="utf-8")
        for name in (EXE, "editor.map", "PE-IMPORTS.txt"):
            (work / name).replace(out / name)
        print(hashes[-1], "(x86 PE32 GUI 4.0; GDI32, KERNEL32, USER32)")


# Independent fixture: hand-encoded strings, not generated by the C writer.
# VCPics:Warm Art.iff, Sub/cool.16; third record uses both earlier names.
FIXTURE = HDR + (
    b"Fixture Author\n7\n3\nWDQjdt;Xbsn!Bsu/jgg\nZIP\nTvc0dppm/27\nZIP\n"
    b"WDQjdt;Xbsn!Bsu/jgg\nTvc0dppm/27\n0\n0\n0\n3\n"
    b"0\n1\n6\n0\n40\n30\n20\n10\n0\nNOTEXT\n"
    b"50\n2\n7\n19\n2\n3\n4\n5\n0\nTubs!Mjhiu\n"
    b"80\n1\n8\n0\n0\n0\n0\n0\n0\nNOTEXT\n"
)
TILDE_FIXTURE = (FIXTURE.replace(b"WDQjdt;Xbsn!Bsu/jgg", b"WDQjdt;XBSN\x7f2/JGG")
                 .replace(b"Tubs!Mjhiu", b"Tubs!Mjhiu\x7f"))

# Source-derived field samples, not output from vc_at. Each moving sample is
# (tick since start, total rows stepped); None means End has already run.
# CalculateParam + DoDisplay: steps 256, 86, 7, 6, 2 and 1 respectively.
# Slides, Scroll and Reveal share these field samples and placement lengths.
SLIDE_SAMPLES = {
    1: ((-1, 0), (0, None), (1, None)),
    2: ((-1, 0), (0, 172), (1, None), (2, None)),
    19: ((-1, 0), (0, 14), (8, 126), (17, 252), (18, None)),
    25: ((-1, 0), (0, 12), (10, 132), (20, 252), (21, None)),
    65: ((-1, 0), (0, 4), (31, 128), (62, 252), (63, None)),
    255: ((-1, 0), (0, 2), (63, 128), (126, 254), (127, None)),
}

# MainLoop dispatches Bodge2 at field 0, then a first slide at field 1.
# Independent end-of-tick samples: one update at tick 0, then two per tick.
FIRST_SLIDE_SAMPLES = {
    1: ((0, None), (1, None)),
    2: ((0, 86), (1, None), (2, None)),
    19: ((0, 7), (8, 119), (17, 245), (18, None)),
    25: ((0, 6), (10, 126), (20, 246), (21, None)),
    65: ((0, 2), (31, 126), (63, 254), (64, None)),
    255: ((0, 1), (63, 127), (126, 253), (127, None)),
}


def test():
    compiler = shutil.which(os.environ.get("CC", "gcc"))
    if not compiler:
        raise ValueError("put GCC or Clang on PATH, or set CC")
    with tempfile.TemporaryDirectory(dir=local_dir(WORK)) as folder:
        work = Path(folder)
        driver, path, output = (work / name for name in ("model.exe", "input.vid", "output.vid"))
        run(Path(compiler), "-std=c90", "-pedantic", "-Wall", "-Wextra", "-Werror",
            *(str(ROOT / "editor" / name) for name in ("model_test.c", "vc10.c")), "-o", str(driver),
            cwd=work, env=None)

        def parse(data):
            path.write_bytes(data)
            return subprocess.run([driver, path, output], capture_output=True, text=True,
                                  timeout=10)

        for data in (FIXTURE, FIXTURE.replace(b"\n", b"\r\n")):
            result = parse(data)
            require(result.returncode == 0 and output.read_bytes() == FIXTURE,
                    f"active VC10 fixture round-trip: {result.stdout} {result.stderr}")
            frames = {r[0]: r[1:] for r in
                      (tuple(map(int, ln.split())) for ln in result.stdout.splitlines())}
            # a=19 -> 7 rows per field, 14 per tick, starting at 255.
            require({k: frames[k] for k in (0, 49, 50, 58, 67, 68, 69, 80)} == {
                0: (6, 0, 256, 0, 0), 49: (6, 0, 256, 0, 0),
                50: (6, 7, 241, 0, 0), 58: (6, 7, 129, 0, 0),
                67: (6, 7, 3, 0, 0), 68: (7, 0, 256, 0, 0),
                69: (7, 0, 256, 0, 0), 80: (8, 0, 256, 0, 0),
            }, "source-derived cut/slide frame geometry")
        print("PASS active LF/CRLF fixture: two ordinary screens and one pair, byte-exact LF output, frame geometry")
        for data in (TILDE_FIXTURE, TILDE_FIXTURE.replace(b"\n", b"\r\n")):
            result = parse(data)
            require(result.returncode == 0 and output.read_bytes() == TILDE_FIXTURE,
                    f"shifted '~' in WARM~1.IFF (ordinary and paired) and Star Light~: {result.stdout}")
        print("PASS active LF/CRLF fixture: shifted '~' in short-style picture name and effect text")
        for effect in range(2, 10):
            for duration, samples in SLIDE_SAMPLES.items():
                data = (TILDE_FIXTURE.replace(b"50\n2\n7\n19\n",
                                             f"50\n{effect}\n7\n{duration}\n".encode("ascii"))
                        .replace(b"80\n1\n8\n", b"400\n1\n8\n"))
                for encoded in (data, data.replace(b"\n", b"\r\n")):
                    result = parse(encoded)
                    require(result.returncode == 0 and output.read_bytes() == data,
                            f"transition {effect}, a={duration}: fields did not round-trip")
                    frames = {r[0]: r[1:] for r in
                              (tuple(map(int, ln.split())) for ln in result.stdout.splitlines())}
                    for elapsed, moved in samples:
                        if elapsed < 0 or (effect in (5, 7, 9) and duration == 1):
                            expected = (6, 0, 256, 0, 0)
                        elif moved is None:
                            expected = (7, 0, 256, 0, 0)
                        else:
                            expected = {
                                2: (6, 7, 255 - moved, 0, 0),
                                3: (7, 6, moved, 256 - moved, moved),
                                4: (6, 7, 255 - moved, moved + 1, 255 - moved),
                                5: (7, 6, moved, 0, 0),
                                6: (6, 7, 255 - moved, moved + 1, 0),
                                7: (7, 6, moved, 256 - moved, 0),
                                8: (6, 7, 255 - moved, 0, 255 - moved),
                                9: (7, 6, moved, 0, moved),
                            }[effect]
                        require(frames[50 + elapsed] == expected,
                                f"transition {effect}, a={duration}, tick {50 + elapsed}: "
                                f"{frames[50 + elapsed]} != {expected}")
                    require(frames[400] == (8, 0, 256, 0, 0), "following Cut")
                for invalid in (0, 256, 65535):
                    bad = data.replace(f"50\n{effect}\n7\n{duration}\n".encode("ascii"),
                                       f"50\n{effect}\n7\n{invalid}\n".encode("ascii"))
                    require(parse(bad).returncode == 1,
                            f"transition {effect} accepted invalid duration {invalid}")
                if effect >= 6:
                    # A following transition starts with the held output, not
                    # the prior target when a downward one-tick swap was skipped.
                    following = data.replace(b"400\n1\n8\n0\n", b"400\n2\n8\n19\n")
                    result = parse(following)
                    require(result.returncode == 0, "following transition rejected")
                    frames = {r[0]: r[1:] for r in
                              (tuple(map(int, ln.split())) for ln in result.stdout.splitlines())}
                    base = 6 if effect in (7, 9) and duration == 1 else 7
                    require(frames[399] == (base, 0, 256, 0, 0) and
                            frames[400] == (base, 8, 241, 0, 0) and
                            frames[418] == (8, 0, 256, 0, 0),
                            f"following transition after ID {effect}, a={duration}")
        print("PASS slides/Scroll/Reveal IDs 2-9: exact LF/CRLF fields and source row offsets at durations "
              "1/2/19/25/65/255; invalid durations; atomic placement rejection and legal boundaries")
        for effect in range(2, 10):
            for duration, samples in FIRST_SLIDE_SAMPLES.items():
                # Remove the initial Cut: the outgoing picture is startup black.
                data = (FIXTURE.replace(b"0\n0\n0\n3\n0\n1\n6\n0\n40\n30\n20\n10\n0\nNOTEXT\n",
                                        b"0\n0\n0\n2\n")
                        .replace(b"50\n2\n7\n19\n",
                                 f"0\n{effect}\n7\n{duration}\n".encode("ascii"))
                        .replace(b"80\n1\n8\n", b"400\n1\n8\n"))
                for start in (0, 1):
                    encoded = data.replace(f"0\n{effect}\n7\n".encode("ascii"),
                                           f"{start}\n{effect}\n7\n".encode("ascii"))
                    result = parse(encoded)
                    require(result.returncode == 0 and output.read_bytes() == encoded,
                            f"first transition {effect}, a={duration}, start={start}: round-trip")
                    frames = {r[0]: r[1:] for r in
                              (tuple(map(int, ln.split())) for ln in result.stdout.splitlines())}
                    # A first cue at tick 1 is not delayed: Bodge2 is already done.
                    for elapsed, moved in (SLIDE_SAMPLES[duration] if start else samples):
                        if elapsed < 0 or (effect in (5, 7, 9) and duration == 1):
                            expected = (0, 0, 256, 0, 0)
                        elif moved is None:
                            expected = (7, 0, 256, 0, 0)
                        else:
                            expected = {
                                2: (0, 7, 255 - moved, 0, 0),
                                3: (7, 0, moved, 256 - moved, moved),
                                4: (0, 7, 255 - moved, moved + 1, 255 - moved),
                                5: (7, 0, moved, 0, 0),
                                6: (0, 7, 255 - moved, moved + 1, 0),
                                7: (7, 0, moved, 256 - moved, 0),
                                8: (0, 7, 255 - moved, 0, 255 - moved),
                                9: (7, 0, moved, 0, moved),
                            }[effect]
                        require(frames[start + elapsed] == expected,
                                f"first transition {effect}, a={duration}, tick {start + elapsed}: "
                                f"{frames[start + elapsed]} != {expected}")
                    require(frames[400] == (8, 0, 256, 0, 0), "startup shifted later Cut")
        print("PASS first transitions IDs 2-9: startup field exception at 1/2/19/25/65/255, "
              "no delay at tick 1, later Cut unchanged")
        rejects = [
            ("UTF-8 header", FIXTURE.replace(b"\xa9", b"\xc2\xa9")),
            ("old-style fields", HDR + b"7\nVCPics:fake.16\n0\n"),
            ("truncated", FIXTURE[:-1]),
            ("extra data", FIXTURE + b"0\n"),
            ("embedded NUL", FIXTURE.replace(b"Fixture Author", b"Fixture\0Author")),
            ("oversized author", FIXTURE.replace(b"Fixture Author", b"A" * 150)),
            ("overflow", FIXTURE.replace(b"\n50\n", b"\n99999999999\n")),
            ("too many screens", FIXTURE.replace(b"\n7\n3\n", b"\n7\n95\n", 1)),
            ("unsupported effect", FIXTURE.replace(b"50\n2\n7\n", b"50\n10\n7\n")),
            ("special screen", FIXTURE.replace(b"50\n2\n7\n", b"50\n2\n1\n")),
            ("dangling screen ID", FIXTURE.replace(b"50\n2\n7\n", b"50\n2\n9\n")),
            ("unresolved pair", FIXTURE.replace(b"Tvc0dppm/27\n0\n", b"yz{\n0\n")),
            ("vector", FIXTURE.replace(b"\n0\n0\n0\n3\n", b"\n1\n0\n0\n3\n", 1)),
            ("object ref", FIXTURE.replace(b"\n5\n0\nTubs", b"\n5\n1\nTubs")),
            ("bad text byte", FIXTURE.replace(b"Tubs!Mjhiu", b"Tubs Mjhiu")),
            ("bad filename byte", TILDE_FIXTURE.replace(b"\x7f2/JGG", b"\x802/JGG")),
            ("bad duration", FIXTURE.replace(b"\n19\n2\n", b"\n0\n2\n")),
            ("overlap", FIXTURE.replace(b"\n80\n1\n8\n", b"\n51\n1\n8\n")),
            ("out of order", FIXTURE.replace(b"\n80\n1\n8\n", b"\n1\n1\n8\n")),
        ]
        for path_name in ("C:\\outside.iff", "/outside.iff", "../outside.iff", "sub/..",
                          "Other:fake.iff", "sub/AUX.txt", "nested/NUL .iff", "one.iff."):
            encoded = bytes(value + 1 for value in path_name.encode("ascii"))
            rejects.append((path_name, FIXTURE.replace(b"WDQjdt;Xbsn!Bsu/jgg", encoded)))
        for name, data in rejects:
            require(parse(data).returncode == 1, f"malformed VC10 accepted: {name}")
        print(f"PASS {len(rejects)} malformed, unsupported and unsafe reference cases")

        # Same native routines as the GUI, with fault injection only in this driver.
        local_driver = work / "local.exe"
        run(Path(compiler), "-Wall", "-Wextra", "-Werror", "-Wno-cast-function-type",
            *(str(ROOT / "editor" / name) for name in ("local_test.c", "vc10.c")),
            "-o", str(local_driver), "-luser32", cwd=work, env=None)
        pinned, alternate = work / "pinned", work / "alternate"
        pinned.mkdir()
        alternate.mkdir()
        (alternate / "test.vid").write_bytes(b"untouched outside the pinned workspace")
        private = pinned / "private.vid"
        private.write_bytes(b"old")
        system = Path(os.environ["SystemRoot"]) / "System32"
        icacls = system / "icacls.exe"
        account = run(system / "whoami.exe", "/user", "/fo", "csv", "/nh", cwd=work, env=None)
        sid = next(csv.reader(account.strip().splitlines()))[1]
        run(icacls, private, "/grant:r", f"*{sid}:F", cwd=work, env=None)
        run(icacls, private, "/inheritance:r", cwd=work, env=None)
        acl_before = run(icacls, private, cwd=work, env=None)
        ordinary = pinned / "Long Project File.vid"
        ordinary.write_bytes(b"old")
        inherited = run(icacls, ordinary, cwd=work, env=None)
        notes = pinned / "notes.vid"
        notes.write_bytes(b"old")
        stream = Path(f"{notes}:annotations")
        stream.write_bytes(b"scratch project notes\n")
        print(run(local_driver, pinned, alternate, cwd=work, env=None), end="")
        require(run(icacls, private, cwd=work, env=None) == acl_before,
                "refusal changed the private project's DACL")
        require(run(icacls, ordinary, cwd=work, env=None) == inherited,
                "ordinary replacement changed the project's DACL")
        require(notes.read_bytes() == b"old" and stream.read_bytes() == b"scratch project notes\n",
                "refusal changed the main file or its named stream")
        print("PASS refused replacement retained the scratch project's main and auxiliary bytes")
        require({p.name: p.read_bytes() for p in pinned.iterdir()} ==
                {"test.vid.bak": b"old", "warning.vid": b"new", "warning.vid.bak": b"old",
                 private.name: b"old", ordinary.name: b"new", notes.name: b"old", "LIT~1.VID": b"new"},
                "wrong pinned files after controlled failures (including staging cleanup)")
        require({p.name: p.read_bytes() for p in alternate.iterdir()} ==
                {"test.vid": b"untouched outside the pinned workspace"},
                "save touched the alternate scratch directory")
        print("PASS NT pinned saves despite synthetic path change; publish failure, rollback, retained backups and cleanup warning")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def smoke():
    from editor_smoke import exercise

    out = local_dir(WORK)
    exe = out / EXE
    pe_headers(exe.read_bytes())
    digest = sha256(exe)
    require(f"{digest}  {EXE}\n" in (out / "PE-IMPORTS.txt").read_text(encoding="utf-8"),
            "run build first")
    with tempfile.TemporaryDirectory(dir=out, prefix="Workspace With Spaces ") as folder:
        work = Path(folder)
        for name, (_, input_hash, _) in zip(NAMES, FIXTURE_PINS):
            copy_fixture(name, input_hash, work)
        exercise(exe, digest, work, out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    steps = {fn.__name__: fn for fn in (build, test, smoke)}
    parser.add_argument("command", choices=steps)
    try:
        steps[parser.parse_args().command]()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"editor: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
